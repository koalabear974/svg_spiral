function dmcHexToRgb(hex) {
  const h = hex.replace('#','');
  return { r: parseInt(h.slice(0,2),16), g: parseInt(h.slice(2,4),16), b: parseInt(h.slice(4,6),16) };
}
function dmcColorDist(h1, h2) {
  const a = dmcHexToRgb(h1), b = dmcHexToRgb(h2);
  const dr = a.r-b.r, dg = a.g-b.g, db = a.b-b.b;
  const rm = (a.r+b.r)/2;
  return Math.sqrt((2+rm/256)*dr*dr + 4*dg*dg + (2+(255-rm)/256)*db*db);
}
function getKitSet() {
  const raw = localStorage.getItem('xsMyKit') || '';
  return new Set(raw.split(/[\s,]+/).map(s=>s.trim().toUpperCase()).filter(Boolean));
}
function findClosestDMC(hex, n) {
  return DMC_PALETTE
    .map(([id,name,h]) => ({ id, name, hex:h, dist: dmcColorDist(hex, h) }))
    .sort((a,b) => a.dist-b.dist)
    .slice(0, n);
}
